//! The editor marks shown by the toolbar picker: each editor's own app
//! icon, rasterized to 32x32 (drawn at Retina, one sprite pixel per
//! device pixel) and 16x16 (drawn at 1x). Icons are quantized to a small
//! palette and stored as scanlines of palette keys, so the picker draws
//! hard-edged rects instead of carrying a texture. Sources: each app's
//! .icns / favicon: Gram, Zed, CLion (their app bundles), VS Code and
//! Cursor (their favicons). The generic badge is hand-drawn.

/// One rasterized mark at one resolution.
pub struct Sprite {
    /// Scanlines of palette keys; `.` is transparent. The row count is the
    /// grid size (32 or 16).
    pub rows: &'static [&'static str],
    /// (key, colour) for every key used by `rows`.
    pub palette: &'static [(u8, imgui::ImColor32)],
}

/// A mark at both resolutions.
pub struct Mark {
    /// 32x32 art, sharp when the framebuffer has >= 2x device pixels.
    pub hi: Sprite,
    /// 16x16 art for 1x displays.
    pub lo: Sprite,
}

