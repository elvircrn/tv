impl Sprite {
    /// Draw into a `size`-square box whose top-left is (`x`, `y`), with cell
    /// boundaries snapped to whole device pixels: `fb_scale` is the number
    /// of device pixels per logical pixel, so a 32x32 sprite is one sprite
    /// pixel per device pixel on a Retina framebuffer.
    pub fn draw(&self, dl: &imgui::DrawListMut, x: f32, y: f32, size: f32, fb_scale: f32) {
        let grid = self.rows.len();
        let dev_x = (x * fb_scale).round();
        let dev_y = (y * fb_scale).round();
        let dev_size = (size * fb_scale).round().max(1.0);
        let edge = |origin: f32, i: usize| origin + (i as f32 * dev_size / grid as f32).round();
        for (row_i, row) in self.rows.iter().enumerate() {
            let keys = row.as_bytes();
            debug_assert_eq!(keys.len(), grid);
            let y0 = edge(dev_y, row_i) / fb_scale;
            let y1 = edge(dev_y, row_i + 1) / fb_scale;
            let mut start = 0;
            while start < keys.len() {
                let key = keys[start];
                let mut end = start + 1;
                while end < keys.len() && keys[end] == key {
                    end += 1;
                }
                if key != b'.' {
                    if let Some(&(_, color)) = self.palette.iter().find(|(k, _)| *k == key) {
                        let x0 = edge(dev_x, start) / fb_scale;
                        let x1 = edge(dev_x, end) / fb_scale;
                        // Non-antialiased so adjacent cells meet on a hard
                        // edge instead of a halo.
                        dl.add_rect_filled_multicolor([x0, y0], [x1, y1], color, color, color, color);
                    }
                }
                start = end;
            }
        }
    }
}

/// The mark for `editor`, with the same aliases as the picker labels.
pub fn mark_for(editor: &str) -> &'static Mark {
    match editor {
        "gram" => &GRAM,
        "code" | "vscode" => &VSCODE,
        "cursor" => &CURSOR,
        "zed" => &ZED,
        "clion" => &CLION,
        _ => &GENERIC,
    }
}
